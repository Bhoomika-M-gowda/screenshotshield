"""Runs every synthetic sample through the real pipeline and writes docs/TEST_RESULTS.md (measured, not hand-written numbers)."""
import os, sys, tempfile
HERE = os.path.dirname(__file__)
sys.path.insert(0, os.path.join(HERE, "..", "backend")); sys.path.insert(0, HERE)
import make_samples
from analyzer import analyze_image

EXPECT = {
 "01_normal.jpg": ("Genuine, single JPEG save", None),
 "02_modified_text.jpg": ("Amount re-typed, re-saved at higher JPEG quality", make_samples.AMOUNT_BOX),
 "02b_spliced_text.jpg": ("Amount replaced by a crop with different compression", make_samples.AMOUNT_BOX),
 "03_modified_image_region.jpg": ("Logo area replaced by a noisy pasted patch", make_samples.LOGO_BOX),
 "04_compressed.jpg": ("Genuine but heavily/repeatedly compressed", None),
 "05_no_exif.png": ("Genuine PNG, no EXIF", None),
 "06_modified_text_editor_tag.jpg": ("Amount re-typed + 'Adobe Photoshop' EXIF tag", make_samples.AMOUNT_BOX),
}

def hit(box, regs):
    for r in regs:
        b = r["bbox"]
        if not (b["x"] + b["w"] < box[0] or b["x"] > box[2] or b["y"] + b["h"] < box[1] or b["y"] > box[3]):
            return r["id"]
    return None

paths = make_samples.generate(os.path.join(HERE, "samples"))
lines = ["# Measured test results (synthetic samples)", "",
         "Generated by `python tests/run_evaluation.py`. All images are synthetic payment screenshots created by `tests/make_samples.py`.", "",
         "| Sample | Ground truth | Score | Category | Region over edit? | Flagged regions | Outcome |", "|---|---|---|---|---|---|---|"]
for n, p in paths.items():
    r = analyze_image(p, n, tempfile.mkdtemp())
    truth, box = EXPECT[n]
    regs = r["regions"]["regions"]
    h = hit(box, regs) if box else None
    cat = r["risk"]["category"]
    if box is None:
        out = "Correct (no false alarm)" if cat == "Low" else f"FALSE POSITIVE ({cat})"
    elif h and cat != "Low":
        out = "Detected + localised"
    elif h:
        out = "Edit highlighted (low-confidence) but overall score Low - partial"
    elif cat != "Low":
        out = "Flagged, but not at the edit (partial)"
    else:
        out = "MISSED (false negative)"
    lines.append(f"| {n} | {truth} | {r['risk']['score']} | {cat} | {('#%d' % h) if h else ('n/a' if box is None else 'no')} | {len(regs)} | {out} |")
open(os.path.join(HERE, "..", "docs", "TEST_RESULTS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
